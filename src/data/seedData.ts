  const openingStock = 60 + ((idx * 7) % 50);
  const soldQuantity = Math.floor(openingStock * (0.4 + ((idx * 3) % 4) * 0.1));
  const wastage = idx % 5 === 0 ? 3 : idx % 7 === 0 ? 2 : 0;
  const remainingStock = Math.max(0, openingStock - soldQuantity - wastage);
  
